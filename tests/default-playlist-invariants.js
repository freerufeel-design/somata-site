const fs=require('fs');
const path=require('path');
const assert=require('assert');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');

const html=read('index.html');
const app=read('js/legacy/app-c.js');

const importPos=html.indexOf('id="btnImportPlaylistProjects"');
const defaultPos=html.indexOf('id="btnOpenDefaultPlaylist"');
const separatorPos=html.indexOf('<div class="menu-separator"></div>',importPos);
assert.ok(importPos>=0,'Import-projects menu item missing');
assert.ok(defaultPos>importPos,'Default-playlist item must appear below Import projects into playlist');
assert.ok(separatorPos>defaultPos,'Default-playlist item must stay in the playlist section of File menu');
assert.ok(html.includes('<button id="btnOpenDefaultPlaylist">Открыть стандартный плейлист</button>'),'Default playlist menu label missing');
assert.ok(app.includes("responseMeta=await readTextFromRelativeFile('default.plist')"),'Default playlist must load default.plist automatically');
assert.ok(app.includes("new URL('../../', scriptUrl)"),'Default playlist path must be rooted beside index.html using the loaded app-c script URL');
assert.ok(!app.includes('somata-default-playlist'),'Default playlist must not use a file picker or stored file-handle permission');
assert.ok(!app.includes('pickDefaultPlaylistWithInput'),'Default playlist must not fall back to an input-file dialog');
assert.ok(app.includes("await loadPlaylistDocument(parsed,'default.plist',null)"),'Default playlist must use the normal playlist activation pipeline without a file handle');
assert.ok(app.includes("document.getElementById('btnOpenDefaultPlaylist')?.addEventListener('click', openDefaultPlaylist)"),'Default playlist menu button is not wired');
assert.ok(app.includes("console.error('[Somata default.plist] OPEN FAILED',diagnostic,err)"),'Default playlist errors must include structured diagnostics in the in-app error console');
assert.ok(app.includes("stage='download'")&&app.includes("stage='parse'")&&app.includes("stage='apply'"),'Default playlist diagnostics must identify download/parse/apply stage');
assert.ok(app.includes('HTTP ${response.status}'),'HTTP status must be reported when default.plist cannot be loaded');
assert.ok(app.includes('Сервер вернул HTML вместо default.plist'),'SPA/404 HTML fallback must be diagnosed explicitly');
assert.ok(app.includes("showShortcutToast('default.plist не открыт · причина в консоли (клик по FPS)')"),'Failure must point the user to the FPS error console');
assert.ok(html.includes('js/legacy/app-c.js?v=20261012-v7320'),'Default playlist code must be cache-busted for 7.3.9');
assert.ok(app.includes("cache:'default'"),'Deployed default.plist should be allowed to use the browser HTTP cache');
assert.ok(!app.includes('project: cloneData(project)'),'Playlist open must not JSON-clone every freshly parsed project');
assert.ok(app.includes('Promise.allSettled(list.map(async file=>'),'Bulk project import should read/parse selected files concurrently');
const projectPos=html.indexOf('id="btnSaveAsJSON"');
const sectionPos=html.indexOf('menu-separator menu-section-separator');
const playlistPos=html.indexOf('id="btnNew"');
assert.ok(projectPos>=0&&sectionPos>projectPos&&playlistPos>sectionPos,'File menu must show Project actions, a straight separator, then Playlist actions');
console.log('Default playlist invariants OK');
