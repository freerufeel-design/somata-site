const {createBrowserHarness,uncaughtExceptions}=require('./lib/browser-harness');
const assert=(c,m)=>{if(!c)throw new Error(m)};
(async()=>{
  const h=await createBrowserHarness({disableGpu:true,evalTimeoutMs:25000});
  const baseline=uncaughtExceptions(h.events).length;
  try{
    const out=await h.evaluate(`(async()=>{
      const sleep=ms=>new Promise(r=>setTimeout(r,ms));
      const clean=t=>String(t||'').replace(/[▾✓]/g,'').replace(/\\s+/g,' ').trim();
      // Open all three control planes so their real group UI exists.
      document.getElementById('btnMorphSettings')?.click();await sleep(30);syncMorphProfileUI();
      document.getElementById('btnRandomSettings')?.click();await sleep(30);syncOrangeMorphProfileUI();
      if(document.getElementById('audioRoutingPanel')?.classList.contains('hidden'))document.getElementById('btnAudioRouting')?.click();await sleep(30);
      state.audioReactive.routingTarget='master';renderAudioRoutingPanel();await sleep(20);
      const shared=SomataParameterRegistry.sharedRoutingGroups();
      const blue=[...document.querySelectorAll('#morphRoutingGroups .audio-route-group-btn')].map(b=>b.dataset.morphRoutingGroup||clean(b.textContent));
      const orange=[...document.querySelectorAll('#orangeMorphRoutingGroups .audio-route-group-btn')].map(b=>b.dataset.orangeGroup||clean(b.textContent));
      const audio=[...document.querySelectorAll('#audioRoutingPanel .audio-routing-tools .audio-route-group-btn')].filter(b=>!b.closest('.audio-route-group').classList.contains('hidden')).map(b=>clean(b.textContent));
      const fillAudioVisible=!document.getElementById('audioGroupFill')?.closest('.audio-route-group')?.classList.contains('hidden');

      // RMB on one real left parameter must expose Blue + Orange + Audio.
      const def=SomataParameterRegistry.get('layer.strokeWidth'),el=document.getElementById(def.ui.mainId),host=el.closest('.blue-morph-range-host')||el;
      const rr=host.getBoundingClientRect();host.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,button:2,clientX:rr.left+4,clientY:rr.top+4}));await sleep(10);
      const popup=document.getElementById('parameterRoutingContextMenu');
      const rmb={blue:!!popup.querySelector('.routing-morph'),orange:!!popup.querySelector('.routing-orange'),audio:!!popup.querySelector('.parameter-routing-popup-audio')};
      popup.classList.add('hidden');

      // Select Solar Rosette and start real Orange.
      const os=document.getElementById('orangeMorphProfileSelect');os.value='orange-solar-rosette';os.dispatchEvent(new Event('change',{bubbles:true}));await sleep(40);
      if(runtimeState.minimalMorph.active)activeStopMinimalMorphing(false);
      document.getElementById('btnMinimalMorph')?.click();await sleep(120);
      const orangeStarted=runtimeState.minimalMorph.active===true;

      // Real RMB Orange toggle while active must not stop it.
      const beforeRoute=SomataOrangeParameterRoutingUI.state('layer.strokeWidth').active;
      SomataOrangeParameterRoutingUI.setActive('layer.strokeWidth',!beforeRoute);await sleep(30);
      const afterRoute={active:SomataOrangeParameterRoutingUI.state('layer.strokeWidth').active,running:runtimeState.minimalMorph.active===true};
      // Keep it active and force exact range so generation proves the panel is functional.
      SomataOrangeParameterRoutingUI.setActive('layer.strokeWidth',true);SomataOrangeMorphProfiles.setRange(state.minimalMorph,state.randomOptions,state.randomLayerCount,'layer.strokeWidth',7,7);
      // Force next static Orange generation through the real dice while Orange is active.
      document.getElementById('btnRandomPreset')?.click();await sleep(160);
      const diceRunning=runtimeState.minimalMorph.active===true;
      const widths=(state.layers||[]).map(l=>Number(l.strokeWidth)).filter(Number.isFinite);

      // Lamps generated by a lamp-owning Orange recipe must always use adaptive brightness.
      const lampLayers=(state.layers||[]).filter(l=>getLayerLampsEnabled(l));
      const adaptive=lampLayers.map(l=>({on:l.lamps?.adaptiveBrightness===true,adjust:l.lamps?.adaptiveAdjustBrightness===true,strength:Number(l.lamps?.adaptiveStrength)||0}));

      // Manual left toggle persists and Orange keeps running across the next dice transition.
      const lampToggle=document.getElementById('showLamps');
      if(lampToggle.checked!==false){lampToggle.checked=false;lampToggle.dispatchEvent(new Event('change',{bubbles:true}));await sleep(25);}
      const afterManualOff={running:runtimeState.minimalMorph.active===true,override:state.minimalMorph?.featureOverrides?.lamps};
      // The manual state belongs to Orange as a morph type, not to one preset.
      os.value='orange-crystal-cathedral';os.dispatchEvent(new Event('change',{bubbles:true}));await sleep(45);
      const afterProfileSwitch={running:runtimeState.minimalMorph.active===true,override:state.minimalMorph?.featureOverrides?.lamps};
      document.getElementById('btnRandomPreset')?.click();await sleep(160);
      const afterRegenerate={running:runtimeState.minimalMorph.active===true,allOff:(state.layers||[]).every(l=>!getLayerLampsEnabled(l)),override:state.minimalMorph?.featureOverrides?.lamps};
      if(runtimeState.minimalMorph.active)activeStopMinimalMorphing(false);

      // Blue: changing a live effect must not stop Blue either.
      if(runtimeState.morph.active)activeStopMorphing(false);document.getElementById('btnMorph')?.click();await sleep(100);
      const webToggle=document.getElementById('showWeb');webToggle.checked=!webToggle.checked;webToggle.dispatchEvent(new Event('change',{bubbles:true}));await sleep(35);
      const blueManual={running:runtimeState.morph.active===true,override:state.morph?.featureOverrides?.web};
      if(runtimeState.morph.active)activeStopMorphing(false);
      return{shared,blue,orange,audio,fillAudioVisible,rmb,orangeStarted,beforeRoute,afterRoute,diceRunning,widths,adaptive,lampCount:lampLayers.length,afterManualOff,afterProfileSwitch,afterRegenerate,blueManual};
    })()`,{timeoutMs:25000,label:'7.11.0 shared routing + Orange lifecycle'});
    assert(JSON.stringify(out.blue)===JSON.stringify(out.shared),'Blue group catalog differs from Registry: '+JSON.stringify(out));
    assert(JSON.stringify(out.orange)===JSON.stringify(out.shared),'Orange group catalog differs from Registry: '+JSON.stringify(out));
    assert(JSON.stringify(out.audio)===JSON.stringify(out.shared),'Audio group catalog differs from Registry: '+JSON.stringify(out));
    assert(!out.fillAudioVisible,'legacy separate Fill group is still visible in Audio');
    assert(out.rmb.blue&&out.rmb.orange&&out.rmb.audio,'RMB does not expose all three routing planes');
    assert(out.orangeStarted&&out.afterRoute.running,'Orange stopped while changing a routed parameter');
    assert(out.afterRoute.active!==out.beforeRoute,'Orange RMB/routing toggle did not change state');
    assert(out.diceRunning,'dice stopped Orange Morph');
    assert(out.widths.length&&out.widths.every(v=>Math.abs(v-7)<1e-6),'Orange range did not drive generated stroke width: '+JSON.stringify(out.widths));
    assert(out.lampCount>0,'lamp-owning Orange preset generated no lamps');
    assert(out.adaptive.every(x=>x.on&&x.adjust&&x.strength>=80),'Orange lamps lost adaptive brightness: '+JSON.stringify(out.adaptive));
    assert(out.afterManualOff.running&&out.afterManualOff.override===false,'manual lamp OFF stopped Orange or was not remembered');
    assert(out.afterProfileSwitch.running&&out.afterProfileSwitch.override===false,'manual lamp OFF was lost when switching Orange preset');
    assert(out.afterRegenerate.running&&out.afterRegenerate.allOff&&out.afterRegenerate.override===false,'manual lamp OFF did not persist through Orange generation');
    assert(out.blueManual.running,'manual effect toggle stopped Blue Morph');
    const errors=uncaughtExceptions(h.events).slice(baseline);assert(!errors.length,'uncaught browser exceptions: '+errors.join(' | '));
    console.log('7.11.0 ORANGE SHARED ROUTING + LIFECYCLE: PASS',out);
  }finally{await h.close();}
})().catch(e=>{console.error('7.11.0 ORANGE SHARED ROUTING + LIFECYCLE: FAIL',e.stack||e);process.exit(1)});
