'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const pipeline=fs.readFileSync(path.join(root,'js/render/main-pipeline.js'),'utf8');
assert.ok(pipeline.includes("if(!visualPlan?.items?.length)continue;"),'Visually empty lamp sets must be treated as a no-op, not a GPU queue failure');
assert.ok(pipeline.includes("copyAlpha=Math.max(0,Math.min(1,Number(effect.instances.alphas?.[li]??1)))"),'Tunnel copy alpha must be normalized before lamp queueing');
assert.ok(pipeline.includes("if(effectiveAlpha<=.001)continue;"),'Fully faded tunnel copies must be skipped before GPU queueing');
assert.ok(pipeline.includes("queueVisualPlan(mainCtx,visualPlan,effectiveAlpha,drawPlan)"),'Only visible lamp copies should reach the GPU queue');
assert.ok(pipeline.includes("drawLampVisualPlan(mainCtx,visualPlan,effectiveAlpha,drawPlan)"),'Explicit Canvas lamp fallback must reuse the normalized visible-copy alpha');
assert.ok(!pipeline.includes("drawLampVisualPlan(mainCtx,visualPlan,set.alphaBase*a,drawPlan)"),'Lamp fallback must not reference the removed raw alpha variable');
console.log('Lamp fade queue invariants OK');
